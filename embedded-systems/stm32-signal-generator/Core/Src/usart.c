void UART_Send_Waveform_Point(uint16_t data)
{
    // 回归文本模式 (FireWater协议)，兼容性最好
    // 使用 sprintf + 块传输，比逐字节 printf 更稳定，适合 921600 高波特率
    char buf[16];
    int len = sprintf(buf, "%d\r\n", data);
    HAL_UART_Transmit(&huart5, (uint8_t*)buf, len, 0xFFFF);
}
